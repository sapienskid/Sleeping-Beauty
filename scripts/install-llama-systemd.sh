#!/usr/bin/env bash
set -Eeuo pipefail

SCRIPT_NAME="$(basename -- "${BASH_SOURCE[0]}")"
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
PROJECT_DIR="$(cd -- "${SCRIPT_DIR}/.." && pwd -P)"
# shellcheck source=scripts/lib/load-dotenv.sh
source "${PROJECT_DIR}/scripts/lib/load-dotenv.sh"
load_dotenv_file "${PROJECT_DIR}/.env"

SERVICE_SRC="${PROJECT_DIR}/systemd/llama-cpp.service"
SERVICE_DST="/etc/systemd/system/llama-cpp.service"
ENV_DST="/etc/default/llama-cpp"

LLAMA_SERVER_BIN="${LLAMA_SERVER_BIN:-/home/sapiens/llama.cpp/build-cuda/bin/llama-server}"
LLAMA_HOST="${LLAMA_HOST:-0.0.0.0}"
LLAMA_PORT="${LLAMA_PORT:-10000}"
MODELS_DIR="${MODELS_DIR:-/home/sapiens/models}"
LLAMA_N_GPU_LAYERS="${LLAMA_N_GPU_LAYERS:-99}"
LLAMA_CONTEXT_SIZE="${LLAMA_CONTEXT_SIZE:-102400}"
LLAMA_PARALLEL="${LLAMA_PARALLEL:-1}"
LLAMA_BATCH_SIZE="${LLAMA_BATCH_SIZE:-512}"
LLAMA_UBATCH_SIZE="${LLAMA_UBATCH_SIZE:-64}"
LLAMA_KV_CACHE_TYPE_K="${LLAMA_KV_CACHE_TYPE_K:-q8_0}"
LLAMA_KV_CACHE_TYPE_V="${LLAMA_KV_CACHE_TYPE_V:-q8_0}"
LLAMA_MODELS_MAX="${LLAMA_MODELS_MAX:-1}"
LLAMA_CACHE_RAM="${LLAMA_CACHE_RAM:-2048}"

log() {
  printf '[%s] %s\n' "$SCRIPT_NAME" "$*" >&2
}

die() {
  log "ERROR: $*"
  exit 1
}

require_command() {
  local cmd="$1"
  command -v "$cmd" >/dev/null 2>&1 || die "Required command not found: $cmd"
}

write_systemd_env_file() {
  quote_env_value() {
    local value="$1"
    value="${value//\\/\\\\}"
    value="${value//\"/\\\"}"
    printf '"%s"' "$value"
  }

  cat > "$ENV_DST" <<EOF
# /etc/default/llama-cpp
# Generated by ${SCRIPT_NAME} from ${PROJECT_DIR}/.env

LLAMA_SERVER_BIN=$(quote_env_value "${LLAMA_SERVER_BIN}")
LLAMA_HOST=$(quote_env_value "${LLAMA_HOST}")
LLAMA_PORT=$(quote_env_value "${LLAMA_PORT}")
LLAMA_MODELS_DIR=$(quote_env_value "${MODELS_DIR}")
LLAMA_N_GPU_LAYERS=$(quote_env_value "${LLAMA_N_GPU_LAYERS}")
LLAMA_CONTEXT_SIZE=$(quote_env_value "${LLAMA_CONTEXT_SIZE}")
LLAMA_PARALLEL=$(quote_env_value "${LLAMA_PARALLEL}")
LLAMA_BATCH_SIZE=$(quote_env_value "${LLAMA_BATCH_SIZE}")
LLAMA_UBATCH_SIZE=$(quote_env_value "${LLAMA_UBATCH_SIZE}")
LLAMA_KV_CACHE_TYPE_K=$(quote_env_value "${LLAMA_KV_CACHE_TYPE_K}")
LLAMA_KV_CACHE_TYPE_V=$(quote_env_value "${LLAMA_KV_CACHE_TYPE_V}")
LLAMA_MODELS_MAX=$(quote_env_value "${LLAMA_MODELS_MAX}")
LLAMA_CACHE_RAM=$(quote_env_value "${LLAMA_CACHE_RAM}")
EOF
}

if [[ "${EUID}" -ne 0 ]]; then
  die "Run as root, for example: sudo ./scripts/install-llama-systemd.sh"
fi

require_command install
require_command systemctl

[[ -f "$SERVICE_SRC" ]] || die "Service file not found: $SERVICE_SRC"

log "Installing systemd unit to ${SERVICE_DST}"
install -D -m 0644 "$SERVICE_SRC" "$SERVICE_DST"

if [[ -f "$ENV_DST" ]]; then
  BACKUP_PATH="${ENV_DST}.bak.$(date +%Y%m%d%H%M%S)"
  log "Backing up existing ${ENV_DST} to ${BACKUP_PATH}"
  cp -a -- "$ENV_DST" "$BACKUP_PATH"
fi

log "Writing environment file to ${ENV_DST}"
install -D -m 0644 /dev/null "$ENV_DST"
write_systemd_env_file

log "Ensuring model directory exists: ${MODELS_DIR}"
install -d -m 0755 "$MODELS_DIR"
chown sapiens:sapiens "$MODELS_DIR"

log "Reloading systemd, enabling and starting llama-cpp.service"
systemctl daemon-reload
systemctl enable --now llama-cpp.service

log "Service status:"
systemctl --no-pager --full status llama-cpp.service
